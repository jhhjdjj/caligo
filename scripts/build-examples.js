/**
 * Generate `web/examples.js` from the programs in `examples/`.
 *
 * The example files are the single source of truth: the CLI can run them, the
 * docs can link to them, and the playground imports the generated module. Each
 * file starts with two metadata comments:
 *
 *   // title: Pipelines
 *   // description: Data flows through |> ...
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const examplesDirectory = path.join(root, "examples");
const target = path.join(root, "web", "examples.js");

const files = readdirSync(examplesDirectory)
  .filter((file) => file.endsWith(".caligo"))
  .sort();

const examples = files.map((file) => {
  const source = readFileSync(path.join(examplesDirectory, file), "utf8").replace(/^\uFEFF/u, "");
  const title = /^\/\/ title:\s*(.+)$/mu.exec(source)?.[1]?.trim() ?? file.replace(/\.caligo$/u, "");
  const description = /^\/\/ description:\s*(.+)$/mu.exec(source)?.[1]?.trim() ?? "";
  const code = source.replace(/^\/\/ (?:title|description):.*\r?\n/gmu, "").trim();
  return { id: file.replace(/\.caligo$/u, ""), title, description, code };
});

const preferred = process.env.CALIGO_DEFAULT_EXAMPLE ?? "hello";
const defaultExample = examples.some((example) => example.id === preferred) ? preferred : examples[0].id;

const banner = "// Generated by scripts/build-examples.js from examples/*.caligo — do not edit by hand.\n\n";
writeFileSync(
  target,
  `${banner}export const EXAMPLES = ${JSON.stringify(examples, null, 2)};\n\nexport const DEFAULT_EXAMPLE = ${JSON.stringify(defaultExample)};\n`,
  "utf8",
);

console.log(`wrote web/examples.js (${examples.length} examples, default: ${defaultExample})`);
